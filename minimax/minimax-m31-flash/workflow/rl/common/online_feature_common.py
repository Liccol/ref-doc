#!/usr/bin/env python3
"""Shared online HTTP harness for CP, SP and PP verification.

The harness starts a real ``vllm serve`` process for a baseline and for the
feature variant, then compares OpenAI-compatible completion responses.  A
multi-node run delegates lifecycle management to ``vllm-ascend-serving``'s
``serve_start.py``/``serve_stop.py`` instead of assembling SSH commands here.
"""

from __future__ import annotations

import argparse
import json
import os
import shlex
import subprocess
import sys
import time
import urllib.error
import urllib.request
from contextlib import contextmanager
from dataclasses import dataclass
from pathlib import Path
from typing import Iterator, Sequence

from common.feature_arguments import (
    add_cluster_connection_arguments,
    add_generation_arguments,
    add_report_arguments,
    add_service_arguments,
    add_timeout_argument,
    port_number,
    positive_number,
)


SCRIPT_DIR = Path(__file__).resolve().parent
SERVING_DIR = SCRIPT_DIR.parent.parent / "vllm-ascend-serving" / "scripts"
SERVE_START = SERVING_DIR / "serve_start.py"
SERVE_STOP = SERVING_DIR / "serve_stop.py"

DEFAULT_PROMPTS = (
    "The capital of France is",
    "Explain why the sky is blue in one sentence.",
)
API_ENDPOINTS = ("/v1/completions", "/v1/chat/completions")


class UnsupportedFeature(RuntimeError):
    """Raised when a feature cannot be exercised with the requested topology."""


@dataclass
class ServiceHandle:
    base_url: str
    process: subprocess.Popen | None = None
    log_path: Path | None = None
    remote: bool = False
    launch_command: str | None = None


def add_online_feature_arguments(parser: argparse.ArgumentParser) -> None:
    """Compose generic feature arguments with online launch-specific options."""
    add_service_arguments(parser, require_server=False, model_option=None)
    add_generation_arguments(parser, prompt_input="repeat")
    add_report_arguments(parser, required=False, include_verification_command=False)
    add_cluster_connection_arguments(parser)
    add_timeout_argument(parser, option="--health-timeout", default=1800.0, value_type=positive_number)
    add_timeout_argument(parser, option="--request-timeout", default=600.0, value_type=positive_number)
    parser.add_argument("--baseline-cmd", required=True,
                        help="Baseline `vllm serve ...` command generated by the skill")
    parser.add_argument("--serving-script", default=str(SERVE_START),
                        help="Path to vllm-ascend-serving/scripts/serve_start.py")
    parser.add_argument("--ssh-port", type=port_number, default=22)
    parser.add_argument("--cann-dir", default="/path/to/installation")
    parser.add_argument("--baseline-result", default=None, help="Saved baseline JSON used for comparison")


def split_flags(command: str) -> list[str]:
    lexer = shlex.shlex(command, posix=True)
    lexer.whitespace_split = True
    lexer.commenters = ""
    return list(lexer)


def display_command(command: Sequence[str]) -> str:
    """Return a copy-safe shell command for the UI and JSON evidence.

    Passwords are intentionally redacted before printing.  The command still
    contains every service/topology/feature flag needed to diagnose a bad
    launch, while avoiding leaking credentials into the report or page log.
    """
    values = list(map(str, command))
    for index, token in enumerate(values[:-1]):
        if token in {"--password", "--worker-password"}:
            values[index + 1] = "<redacted>"
    return shlex.join(values)


def _find_model_index(tokens: Sequence[str]) -> int:
    try:
        serve_index = tokens.index("serve")
    except ValueError as exc:
        raise ValueError("baseline command must contain `vllm serve`") from exc
    for index in range(serve_index + 1, len(tokens)):
        token = tokens[index]
        if token != "--" and not token.startswith("-"):
            return index
    raise ValueError("could not find model path after `vllm serve`")


def _flag_value(tokens: Sequence[str], names: set[str], default, cast):
    for index, token in enumerate(tokens):
        for name in names:
            if token == name and index + 1 < len(tokens):
                try:
                    return cast(tokens[index + 1])
                except (TypeError, ValueError):
                    return default
            prefix = name + "="
            if token.startswith(prefix):
                try:
                    return cast(token[len(prefix):])
                except (TypeError, ValueError):
                    return default
    return default


def _has_flag(tokens: Sequence[str], names: set[str]) -> bool:
    return any(token in names or any(token.startswith(name + "=") for name in names)
               for token in tokens)


def parse_baseline(command: str) -> dict:
    tokens = split_flags(command)
    model_index = _find_model_index(tokens)
    return {
        "tokens": tokens,
        "model_index": model_index,
        "model": tokens[model_index],
        "tensor_parallel_size": _flag_value(tokens, {"--tensor-parallel-size", "-tp"}, 1, int),
        "data_parallel_size": _flag_value(tokens, {"--data-parallel-size", "-dp"}, 1, int),
        "pipeline_parallel_size": _flag_value(tokens, {"--pipeline-parallel-size", "-pp"}, 1, int),
        "port": _flag_value(tokens, {"--port", "-p"}, 8000, int),
        "host": _flag_value(tokens, {"--host"}, "127.0.0.1", str),
        "enable_expert_parallel": _has_flag(tokens, {"--enable-expert-parallel", "--enable_expert_parallel"}),
    }


def _strip_pairs(tokens: Sequence[str], remove_flags: set[str]) -> list[str]:
    """Remove feature and endpoint flags while preserving all other baseline args."""
    value_flags = {
        "--host", "--port", "-p", "--tensor-parallel-size", "-tp",
        "--data-parallel-size", "-dp", "--data-parallel-size-local",
        "--data-parallel-start-rank", "--data-parallel-address",
        "--data-parallel-rpc-port", "--pipeline-parallel-size", "-pp",
        "--prefill-context-parallel-size", "--decode-context-parallel-size",
        "--all2all-backend",
    }
    out: list[str] = []
    index = 0
    while index < len(tokens):
        token = tokens[index]
        bare = token.split("=", 1)[0]
        if bare in remove_flags or bare in {"--host", "--port", "-p"}:
            if "=" not in token and bare in value_flags:
                index += 2
            else:
                index += 1
            continue
        out.append(token)
        index += 1
    return out


def build_variant(
    baseline: dict,
    *,
    remove_flags: set[str],
    feature_args: Sequence[str],
    host: str,
    port: int,
) -> list[str]:
    """Build a local ``vllm serve`` argv for one baseline/feature variant."""
    tokens = baseline["tokens"]
    model_index = baseline["model_index"]
    head = list(tokens[: model_index + 1])
    tail = _strip_pairs(tokens[model_index + 1 :], remove_flags)
    # Put feature flags before an optional command separator.
    if "--" in tail:
        marker = tail.index("--")
        tail = tail[:marker] + list(feature_args) + tail[marker:]
    else:
        tail.extend(feature_args)
    return head + tail + ["--host", host, "--port", str(port)]


def _launcher_passthrough(argv: Sequence[str]) -> list[str]:
    """Remove launcher-owned model/topology/endpoint flags from vLLM args."""
    try:
        model_index = _find_model_index(argv)
    except ValueError:
        return list(argv)
    tail = list(argv[model_index + 1 :])
    owned = {
        "--host", "--port", "-p", "--tensor-parallel-size", "-tp",
        "--data-parallel-size", "-dp", "--data-parallel-size-local",
        "--data-parallel-start-rank", "--data-parallel-address",
        "--data-parallel-rpc-port", "--headless",
    }
    value_flags = owned - {"--headless"}
    out: list[str] = []
    index = 0
    while index < len(tail):
        token = tail[index]
        bare = token.split("=", 1)[0]
        if bare in owned:
            index += 2 if "=" not in token and bare in value_flags else 1
            continue
        out.append(token)
        index += 1
    return out


def _connection_args(
    args: argparse.Namespace,
    *,
    include_workers: bool,
    include_worker_hosts: bool = True,
    include_cann: bool = True,
) -> list[str]:
    result = [
        "--host", args.host,
        "--ssh-port", str(args.ssh_port),
        "--user", args.user,
        "--mode", args.connection_mode,
    ]
    if include_cann:
        result.extend(["--cann-dir", args.cann_dir])
    optional = (
        ("--password", args.password),
        ("--key-file", args.key_file),
        ("--container", args.container),
        ("--conda-env", args.conda_env),
    )
    for flag, value in optional:
        if value:
            result.extend([flag, value])
    if include_workers:
        if include_worker_hosts and args.worker_hosts:
            result.extend(["--worker-hosts", args.worker_hosts])
        for flag, value in (
            ("--worker-password", args.worker_password),
            ("--worker-key-file", args.worker_key_file),
            ("--worker-container", args.worker_container),
            ("--worker-conda-env", args.worker_conda_env),
        ):
            if value:
                result.extend([flag, value])
    return result


def _json_from_stdout(stdout: str) -> dict:
    for line in reversed(stdout.splitlines()):
        line = line.strip()
        if not line:
            continue
        try:
            value = json.loads(line)
        except json.JSONDecodeError:
            continue
        if isinstance(value, dict):
            return value
    raise RuntimeError("serve_start.py returned no JSON result")


def _wait_http_ready(base_url: str, timeout: float) -> None:
    deadline = time.time() + timeout
    last_error = ""
    while time.time() < deadline:
        try:
            health = _get_json(base_url.rstrip("/") + "/health", timeout=5)
            if health is None:
                raise RuntimeError("health returned no body")
            _get_json(base_url.rstrip("/") + "/v1/models", timeout=5)
            return
        except Exception as exc:  # noqa: BLE001 - readiness polling
            last_error = str(exc)
            time.sleep(5)
    raise TimeoutError(f"timed out waiting for {base_url}/health and /v1/models: {last_error}")


_NO_PROXY_OPENER = urllib.request.build_opener(urllib.request.ProxyHandler({}))


def _get_json(url: str, *, timeout: float):
    request = urllib.request.Request(url, method="GET")
    try:
        with _NO_PROXY_OPENER.open(request, timeout=timeout) as response:
            raw = response.read().decode("utf-8", errors="replace")
            if not raw:
                return {}
            return json.loads(raw)
    except urllib.error.HTTPError as exc:
        raise RuntimeError(f"GET {url} returned HTTP {exc.code}") from exc


def _post_completion(base_url: str, prompt: str, *, max_tokens: int, timeout: float,
                     endpoint: str = "/v1/completions") -> str:
    payload = {"model": "auto", "max_tokens": max_tokens, "temperature": 0}
    if endpoint == "/v1/chat/completions":
        payload["messages"] = [{"role": "user", "content": prompt}]
    else:
        payload["prompt"] = prompt
    request = urllib.request.Request(
        base_url.rstrip("/") + endpoint,
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    try:
        with _NO_PROXY_OPENER.open(request, timeout=timeout) as response:
            raw = response.read().decode("utf-8", errors="replace")
            if response.status != 200:
                raise RuntimeError(f"completion returned HTTP {response.status}: {raw[:500]}")
            data = json.loads(raw)
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", errors="replace")[:500]
        raise RuntimeError(f"completion returned HTTP {exc.code}: {detail}") from exc
    try:
        choice = data["choices"][0]
        text = str(choice.get("message", {}).get("content", "") if endpoint.endswith("chat/completions")
                   else choice.get("text", ""))
    except (KeyError, IndexError, AttributeError, TypeError) as exc:
        raise RuntimeError(f"completion response has no choices[].text: {data!r}") from exc
    if not text.strip() or "\ufffd" in text:
        raise RuntimeError("completion text is empty or contains replacement characters")
    return text


def _output_text(value) -> str:
    """Normalize baseline JSON entries written by baseline/run_baseline.py."""
    if isinstance(value, dict):
        return str(value.get("text", ""))
    return str(value)


def _start_local(
    command: Sequence[str], *, host: str, port: int, timeout: float, label: str
) -> ServiceHandle:
    env = os.environ.copy()
    for key in ("HTTP_PROXY", "HTTPS_PROXY", "ALL_PROXY", "http_proxy", "https_proxy", "all_proxy"):
        env.pop(key, None)
    log_path = Path.cwd() / f"{label}_{port}.log"
    log_file = log_path.open("w", encoding="utf-8")
    process = subprocess.Popen(
        list(command), env=env, stdout=log_file, stderr=subprocess.STDOUT,
        start_new_session=True,
    )
    try:
        _wait_http_ready(f"http://{host}:{port}", timeout)
    except Exception:
        if process.poll() is None:
            process.terminate()
        log_file.close()
        raise
    log_file.close()
    return ServiceHandle(
        f"http://{host}:{port}", process=process, log_path=log_path,
        launch_command=display_command(command),
    )


def _start_remote(
    baseline: dict,
    args: argparse.Namespace,
    *,
    feature_args: Sequence[str],
    remove_flags: set[str],
    port: int,
) -> ServiceHandle:
    local_command = build_variant(
        baseline, remove_flags=remove_flags, feature_args=feature_args,
        host="0.0.0.0", port=port,
    )
    command = [sys.executable, args.serving_script]
    command.extend(_connection_args(args, include_workers=True))
    command.extend(["--model", baseline["model"]])
    command.extend(["--tp", str(baseline["tensor_parallel_size"])])
    # In multi-node mode serve_start.py probes each node and derives total DP
    # from per-node capacity. Passing the baseline's total --dp would conflict
    # with that topology calculation, so only TP and feature passthrough args
    # are forwarded here.
    command.extend(["--port", str(port), "--health-timeout", str(int(args.health_timeout))])
    command.append("--")
    command.extend(_launcher_passthrough(local_command))
    print(f"[online] launch command: {display_command(command)}", flush=True)
    result = subprocess.run(
        command, capture_output=True, text=True,
        timeout=max(args.health_timeout + 120, 300), check=False,
    )
    if result.returncode != 0:
        raise RuntimeError(
            f"serve_start.py failed with rc={result.returncode}: "
            f"{(result.stdout or '')[-500:]} {(result.stderr or '')[-500:]}"
        )
    data = _json_from_stdout(result.stdout)
    if data.get("status") != "ready":
        raise RuntimeError(f"multi-node service is not ready: {data}")
    base_url = str(data.get("base_url") or f"http://{args.host}:{port}")
    return ServiceHandle(base_url, remote=True, launch_command=display_command(command))


def _stop_remote(args: argparse.Namespace) -> None:
    serving_script = Path(args.serving_script).resolve()
    stop_script = serving_script.with_name("serve_stop.py")
    if not stop_script.is_file():
        stop_script = SERVE_STOP
    command = [sys.executable, str(stop_script)]
    # serve_stop.py discovers the worker list from the persisted cluster state;
    # it accepts worker credentials but not --worker-hosts or --cann-dir.
    command.extend(_connection_args(
        args, include_workers=True, include_worker_hosts=False, include_cann=False,
    ))
    command.append("--force")
    subprocess.run(command, capture_output=True, text=True, timeout=120, check=False)


@contextmanager
def service_scope(
    baseline: dict,
    args: argparse.Namespace,
    *,
    feature_args: Sequence[str],
    remove_flags: set[str],
    label: str,
) -> Iterator[ServiceHandle]:
    host = args.host or "127.0.0.1"
    port = int(args.port or baseline["port"])
    if args.server_url:
        yield ServiceHandle(args.server_url.rstrip("/"))
        return
    if args.worker_hosts:
        if not args.host:
            raise ValueError("--host is required when --worker-hosts is used")
        try:
            handle = _start_remote(
                baseline, args, feature_args=feature_args, remove_flags=remove_flags, port=port,
            )
        except Exception:
            # serve_start.py can fail after preparing a head or one worker.
            # Best-effort force cleanup keeps the next feature from inheriting
            # stale processes/ports while preserving the original exception.
            try:
                _stop_remote(args)
            except Exception:
                pass
            raise
    else:
        command = build_variant(
            baseline, remove_flags=remove_flags, feature_args=feature_args,
            host=host, port=port,
        )
        print(f"[{label}] launch command: {display_command(command)}", flush=True)
        handle = _start_local(command, host=host, port=port, timeout=args.health_timeout, label=label)
    try:
        yield handle
    finally:
        if handle.remote:
            _stop_remote(args)
        elif handle.process is not None:
            if handle.process.poll() is None:
                handle.process.terminate()
                try:
                    handle.process.wait(timeout=60)
                except subprocess.TimeoutExpired:
                    handle.process.kill()
            print(f"[{label}] service stopped; log={handle.log_path}")


def _result_report(args: argparse.Namespace, result: dict) -> None:
    if not args.report:
        return
    path = Path(args.report)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(result, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def _record_command(args: argparse.Namespace, label: str, command: str | None) -> None:
    """Append a redacted command to the per-task evidence log."""
    if not command or not args.report:
        return
    log_path = Path(args.report).parent / "launch_commands.txt"
    log_path.parent.mkdir(parents=True, exist_ok=True)
    with log_path.open("a", encoding="utf-8") as stream:
        stream.write(f"{label}: {command}\n")


def run_online_pair(
    baseline: dict,
    args: argparse.Namespace,
    *,
    feature_name: str,
    remove_flags: set[str],
    feature_args: Sequence[str],
    baseline_args: Sequence[str] = (),
    compare_outputs: bool = True,
) -> int:
    """Run baseline and feature HTTP services, or validate an attached URL."""
    prompts = list(args.prompts or DEFAULT_PROMPTS)
    saved_baseline = None
    if args.baseline_result:
        saved_baseline = json.loads(Path(args.baseline_result).read_text(encoding="utf-8"))
        prompts = list(saved_baseline.get("prompts") or prompts)
    result: dict = {
        "feature": feature_name,
        "mode": "attach" if args.server_url else ("multi-node" if args.worker_hosts else "single-node"),
        "status": "failed",
        "prompts": prompts,
        "baseline_args": list(baseline_args),
        "feature_args": list(feature_args),
        "baseline_result": args.baseline_result,
        "verification_command": display_command([sys.executable, *sys.argv]),
    }
    try:
        if args.server_url:
            with service_scope(
                baseline, args, feature_args=feature_args,
                remove_flags=remove_flags, label=f"{feature_name}_attached",
            ) as service:
                outputs_by_endpoint = {
                    endpoint: [_post_completion(service.base_url, prompt, max_tokens=args.max_tokens,
                                                timeout=args.request_timeout, endpoint=endpoint)
                               for prompt in prompts]
                    for endpoint in API_ENDPOINTS
                }
            result.update({
                "status": "passed_http_only",
                "feature_outputs": outputs_by_endpoint["/v1/completions"],
                "feature_outputs_by_endpoint": outputs_by_endpoint,
                "endpoint_checks": {endpoint: True for endpoint in API_ENDPOINTS},
                "launch_command": service.launch_command,
                "service_url": service.base_url,
            })
            _record_command(args, "VERIFIER", result["verification_command"])
            _record_command(args, "SERVICE", service.launch_command)
            print(f"[{feature_name}] PASS (attached online service; no baseline comparison)")
            _result_report(args, result)
            return 0

        if saved_baseline is None:
            raise ValueError(
                "--baseline-result is required; run scripts/baseline/run_baseline.py first"
            )
        baseline_outputs = [
            _output_text(value)
            for value in saved_baseline.get("outputs", saved_baseline.get("baseline_outputs", []))
        ]
        if len(baseline_outputs) != len(prompts):
            raise ValueError("saved baseline prompt count does not match feature prompts")
        with service_scope(
            baseline, args, feature_args=feature_args,
            remove_flags=remove_flags, label=f"{feature_name}_feature",
        ) as service:
            feature_outputs_by_endpoint = {
                endpoint: [_post_completion(service.base_url, prompt, max_tokens=args.max_tokens,
                                            timeout=args.request_timeout, endpoint=endpoint)
                           for prompt in prompts]
                for endpoint in API_ENDPOINTS
            }
            feature_outputs = feature_outputs_by_endpoint["/v1/completions"]
        raw_baseline_by_endpoint = saved_baseline.get("outputs_by_endpoint", {})
        baseline_by_endpoint = {
            endpoint: [_output_text(value) for value in values]
            for endpoint, values in raw_baseline_by_endpoint.items()
        }
        if "/v1/completions" not in baseline_by_endpoint or "/v1/chat/completions" not in baseline_by_endpoint:
            raise ValueError(
                "baseline JSON 缺少两个 API endpoint 的输出，请重新运行 "
                "scripts/baseline/run_baseline.py"
            )
        mismatches_by_endpoint = {}
        for endpoint in API_ENDPOINTS:
            mismatches_by_endpoint[endpoint] = [
                index for index, (before, after) in enumerate(
                    zip(baseline_by_endpoint[endpoint], feature_outputs_by_endpoint[endpoint])
                ) if compare_outputs and before.strip() != after.strip()
            ]
        mismatches = mismatches_by_endpoint["/v1/completions"]
        result.update({
            "baseline_outputs": baseline_outputs,
            "feature_outputs": feature_outputs,
            "baseline_outputs_by_endpoint": baseline_by_endpoint,
            "feature_outputs_by_endpoint": feature_outputs_by_endpoint,
            "mismatches": mismatches,
            "mismatches_by_endpoint": mismatches_by_endpoint,
            "endpoint_checks": {endpoint: not mismatches_by_endpoint[endpoint] for endpoint in API_ENDPOINTS},
            "launch_command": service.launch_command,
            "service_url": service.base_url,
        })
        _record_command(args, "VERIFIER", result["verification_command"])
        _record_command(args, "SERVICE", service.launch_command)
        if any(mismatches_by_endpoint.values()):
            raise AssertionError(f"online output differs from baseline: {mismatches_by_endpoint}")
        result["status"] = "passed"
        detail = "output matches baseline" if compare_outputs else "both online services returned valid output"
        print(f"[{feature_name}] PASS ({detail})")
        _result_report(args, result)
        return 0
    except UnsupportedFeature as exc:
        result.update({"status": "blocked", "reason": str(exc)})
        print(f"[{feature_name}] BLOCKED: {exc}", file=sys.stderr)
        _result_report(args, result)
        return 2
    except Exception as exc:  # noqa: BLE001 - report runtime evidence to caller
        result.update({"status": "failed", "error": str(exc)})
        print(f"[{feature_name}] FAILED: {exc}", file=sys.stderr)
        _result_report(args, result)
        return 1
